import { expect, test } from "@playwright/test";

test("inventory reuses the table across processing modes and independent recoverable scenarios", async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await page.getByRole("link", { name: "Inventory", exact: true }).click();
  await expect(page).toHaveTitle("HL Fitness Studio | Inventory");
  const table = page.getByRole("table", { name: "Studio inventory", exact: true });
  const parents = table.locator(":scope > tbody > tr[data-parent-row]");
  const ready = () => expect(table).toHaveAttribute("aria-busy", "false");
  await ready();
  await expect(parents).toHaveCount(10);
  await expect(parents.first()).toContainText("S$28.00");
  await expect(page.getByText("1–10 of 100", { exact: true })).toBeVisible();
  const sortPrice = page.getByRole("button", { name: /^Sort by Unit price,/ });
  await sortPrice.focus();
  await sortPrice.press("Enter");
  await sortPrice.press("Enter");
  const clientOrder = await parents.locator("td:nth-child(2)").allTextContents();
  await page.getByRole("combobox", { name: "Processing", exact: true }).selectOption("manual");
  await ready();
  expect(await parents.locator("td:nth-child(2)").allTextContents()).toEqual(clientOrder);
  await page.getByRole("button", { name: "Next page" }).click();
  await ready();
  await expect(page.getByText("11–20 of 100", { exact: true })).toBeVisible();
  await page.getByRole("combobox", { name: "Rows per page" }).selectOption("25");
  await ready();
  await expect(parents).toHaveCount(25);
  await expect(page.getByText("1–25 of 100", { exact: true })).toBeVisible();

  await page.getByRole("combobox", { name: "List response" }).selectOption("error");
  await expect(table.getByRole("alert")).toContainText("Unable to load inventory");
  await page.getByRole("button", { name: "Retry", exact: true }).click();
  await ready();
  await expect(parents).toHaveCount(25);
  await page.getByRole("combobox", { name: "List response" }).selectOption("slow");
  await expect(table).toHaveAttribute("aria-busy", "true");
  await page.getByRole("combobox", { name: "List response" }).selectOption("empty");
  await ready();
  await expect(page.getByText("No inventory items available.", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Next page" })).toBeDisabled();
  await page.getByRole("button", { name: "Reset demo" }).click();
  await ready();
  await expect(page.getByRole("combobox", { name: "Processing", exact: true })).toHaveValue("client");

  await page.getByRole("combobox", { name: "Detail response" }).selectOption("error");
  await ready();
  const expand = page.getByRole("button", { name: "Expand Yoga Mat — Classic stock movements" });
  await expand.focus();
  await expand.press("Enter");
  await expect(table.getByRole("alert")).toContainText("Unable to load stock movements");
  await expect(page.getByRole("button", { name: "Next page" })).toBeEnabled();
  await page.getByRole("button", { name: "Retry details" }).click();
  await expect(page.getByRole("table", { name: "Yoga Mat — Classic stock movements", exact: true })).toBeVisible();
  await expect(parents).toHaveCount(10);
  await page.getByRole("combobox", { name: "Detail response" }).selectOption("empty");
  await ready();
  await expand.click();
  await expect(page.getByText("No stock movements", { exact: true })).toBeVisible();
  await page.getByRole("combobox", { name: "Detail response" }).selectOption("slow");
  await ready();
  await expand.click();
  await expect(page.getByText("Loading details…", { exact: true })).toBeVisible();
  await page.getByRole("combobox", { name: "Detail response" }).selectOption("normal");
  await ready();
  await expect(expand).toHaveAttribute("aria-expanded", "false");

  if ((page.viewportSize()?.width ?? 0) < 600) {
    const region = page.getByRole("region", { name: "Studio inventory, scrollable table" });
    const pinned = parents.first().locator("td:first-child");
    const before = await pinned.boundingBox();
    await region.focus();
    await region.press("ArrowRight");
    await expect.poll(() => region.evaluate(element => element.scrollLeft)).toBeGreaterThan(0);
    await expect(pinned).toHaveCSS("position", "sticky");
    await expect(region).toHaveAttribute("data-scrolled", "true");
    const after = await pinned.boundingBox();
    expect(Math.abs((before?.x ?? -100) - (after?.x ?? 100))).toBeLessThan(1);
    await region.evaluate(element => { element.scrollLeft = 0; });
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expand.click();
  await expect(page.getByRole("table", { name: "Yoga Mat — Classic stock movements", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("inventory.png"), fullPage: true });
  await page.getByRole("link", { name: "Class timetable", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Class timetable", exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
